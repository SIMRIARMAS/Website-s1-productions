// Rebuilds editor/trusted-files.js: the list of outside AI files S1 Studio is allowed to load,
// each with its SHA-256 fingerprint. The service worker refuses any file that isn't on the list
// or whose bytes don't match, so a hacked or changed CDN file can't run in the app.
//
// Run it after changing an AI library version (in ai.js, search.js or the workers):
//   node editor/tools/update-trusted.mjs
// It downloads each package from npm (the same bytes cdn.jsdelivr.net serves) and hashes the files.

import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const PACKAGES = {
  '@huggingface/transformers@3.7.1': [
    'dist/transformers.min.js',
    'dist/ort-wasm-simd-threaded.jsep.mjs',
    'dist/ort-wasm-simd-threaded.jsep.wasm',
  ],
  '@mediapipe/tasks-vision@0.10.14': [
    'vision_bundle.mjs',
    'wasm/vision_wasm_internal.js',
    'wasm/vision_wasm_internal.wasm',
    'wasm/vision_wasm_nosimd_internal.js',
    'wasm/vision_wasm_nosimd_internal.wasm',
  ],
  '@vladmandic/face-api@1.7.15': [
    'dist/face-api.esm.js',
    'model/tiny_face_detector_model-weights_manifest.json',
    'model/tiny_face_detector_model.bin',
    'model/face_landmark_68_model-weights_manifest.json',
    'model/face_landmark_68_model.bin',
    'model/face_recognition_model-weights_manifest.json',
    'model/face_recognition_model.bin',
  ],
};

const work = mkdtempSync(join(tmpdir(), 's1-trusted-'));
const table = {};
try {
  for (const [spec, files] of Object.entries(PACKAGES)) {
    const tgz = execFileSync('npm', ['pack', '--silent', spec], { cwd: work }).toString().trim().split('\n').pop();
    const dir = join(work, tgz.replace(/\.tgz$/, ''));
    execFileSync('mkdir', ['-p', dir]);
    execFileSync('tar', ['xzf', join(work, tgz), '-C', dir]);
    for (const f of files) {
      const bytes = readFileSync(join(dir, 'package', f));
      table[`https://cdn.jsdelivr.net/npm/${spec}/${f}`] = 'sha256-' + createHash('sha256').update(bytes).digest('base64');
    }
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}

const out = `// Generated by editor/tools/update-trusted.mjs. Do not edit by hand.
// Outside files S1 Studio may load, with their SHA-256 fingerprints (checked by sw.js).
self.TRUSTED_FILES = ${JSON.stringify(table, null, 2)};
`;
const target = join(dirname(fileURLToPath(import.meta.url)), '..', 'trusted-files.js');
writeFileSync(target, out);
console.log(`Wrote ${Object.keys(table).length} fingerprints to ${target}`);
